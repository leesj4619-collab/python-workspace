def 골넣은선수출력():
    선수 = ["손흥민", "이강인", "황희찬", "김민재"]
    골수 = [2, 0, 1, 0]

    for   sun   , goal   in zip(  선수   , 골수    ):
        if goal > 0:
            print(f" {sun}    : {   goal  }골")

    # 손흥민 : 2골
    # 황희찬 : 1골

