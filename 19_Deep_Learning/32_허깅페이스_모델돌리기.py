"""
=======================================================
학습 목표
=======================================================
1. 실제 캐글 리뷰 데이터로 허깅페이스 별점 예측 모델 테스트하기
2. 허깅페이스 모델을 로컬에 저장하고 불러오는 방법 익히기
3. 리뷰 입력창 만들어서 실시간으로 별점 예측하기

=======================================================
사전 지식
=======================================================
__label__1 = 부정 리뷰 (별점 1~2점)
__label__2 = 긍정 리뷰 (별점 4~5점)

모델 저장 방식
save_pretrained = 허깅페이스 전용 저장 방식 (폴더로 저장)
                  나중에 from_pretrained 로 불러오기 가능
                  keras .h5 처럼 가중치 저장되는 개념과 동일

저장 폴더 구조
my_model/
  config.json        = 모델 구조 정보
  tokenizer.json     = 토크나이저 정보
  pytorch_model.bin  = 실제 가중치 (h5 와 동일한 역할)
"""

import torch
from transformers import pipeline, AutoTokenizer, AutoModelForSequenceClassification

# =======================================================
# 1. 장치 설정
# =======================================================
장치 = 0 if torch.cuda.is_available() else -1
print(f"사용 장치: {'GPU' if 장치 == 0 else 'CPU'}")

# =======================================================
# 2. 모델 불러오기 + 저장하기
# =======================================================
모델이름 = 'nlptown/bert-base-multilingual-uncased-sentiment'

# 처음 실행할 때만 다운로드, 이후엔 로컬에서 불러옴
토크나이저 = AutoTokenizer.from_pretrained(모델이름)
모델      = AutoModelForSequenceClassification.from_pretrained(모델이름)

# 로컬에 저장 (keras 의 model.save('model.h5') 와 동일한 개념)
저장경로 = './my_star_model'
토크나이저.save_pretrained(저장경로)
모델.save_pretrained(저장경로)
print(f"모델 저장 완료: {저장경로}")

# 저장된 모델 불러오기 (keras 의 load_model('model.h5') 와 동일한 개념)
별점분석기 = pipeline(
    'sentiment-analysis',
    model=저장경로,       # 로컬 경로에서 불러오기
    tokenizer=저장경로,
    device=장치
)
print("저장된 모델 불러오기 완료")

# =======================================================
# 3. 데이터 파일 불러오기
# =======================================================
리뷰목록  = []
정답목록  = []

with open('test_ft.txt', 'r', encoding='utf-8') as f:
    for 줄 in f.readlines()[:100]:  # 100개만
        줄 = 줄.strip()
        if 줄.startswith('__label__1'):
            정답목록.append(1)        # 부정
            리뷰목록.append(줄[12:])  # __label__1 제거
        elif 줄.startswith('__label__2'):
            정답목록.append(2)        # 긍정
            리뷰목록.append(줄[12:])  # __label__2 제거

print(f"불러온 리뷰 수: {len(리뷰목록)}개")

# =======================================================
# 4. 예측 + 정확도 계산
# =======================================================
맞춘개수 = 0

for i, 리뷰 in enumerate(리뷰목록):
    결과  = 별점분석기(리뷰[:512], truncation=True)[0]  # 512자 제한
    별점  = int(결과['label'][0])  # '5 stars' → 5
    정답  = 정답목록[i]

    # label 1~2점 = 부정(1), 3~5점 = 긍정(2) 으로 변환해서 비교
    예측변환 = 1 if 별점 <= 2 else 2
    맞춤    = 'O' if 예측변환 == 정답 else 'X'

    print(f"리뷰  : {리뷰[:60]}")
    print(f"별점  : {별점}점  정답: {'긍정' if 정답 == 2 else '부정'}  {맞춤}")
    print('---')

    if 예측변환 == 정답:
        맞춘개수 += 1

print(f"정확도: {맞춘개수}/{len(리뷰목록)} = {맞춘개수/len(리뷰목록)*100:.1f}%")

# =======================================================
# 5. 직접 리뷰 입력해서 별점 예측
# =======================================================
print("\n리뷰를 입력하면 예상 별점을 알려드립니다 (종료: q)")
print("한국어, 영어 모두 가능합니다")
print('=' * 40)

while True:
    내리뷰 = input("리뷰 입력: ")

    if 내리뷰 == 'q':
        print("종료합니다")
        break

    결과  = 별점분석기(내리뷰)[0]
    별점  = int(결과['label'][0])
    확률  = 결과['score']

    별표  = '★' * 별점 + '☆' * (5 - 별점)

    print(f"예상 별점: {별표} ({별점}점)")
    print(f"확신도   : {확률*100:.1f}%")
    print('---')